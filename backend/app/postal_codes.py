def get_city_and_postal_code(code,ville):
    """Trouve la ville à partir du code postal"""
    code = ''.join(filter(str.isdigit, code))
    ville = str(ville).strip()
    
    if code:
        if code in POSTAL_CODES:
            ville_attendue = POSTAL_CODES.get(code)
        
            if ville_attendue.lower()==ville.lower():
                return 0, code, ville, None
            elif ville_attendue.lower()!=ville.lower() and ville:
                return 1, code, ville, f"Incohérence entre le code postal et la ville."
            else:
                return 2, code, ville_attendue, f"Ville auto-remplie depuis le code postal: {code}"
            
        else :
            return 3, code, ville, f"Le code postal est invalide ou correspond à plusieurs villes." 
        
    elif ville: 
        CITY_TO_POSTAL = {ville.lower(): cp for cp, ville in POSTAL_CODES.items()}
        
        if ville.lower() in CITY_TO_POSTAL:
            code_attendue = CITY_TO_POSTAL.get(ville.lower())
            return 4, code_attendue, ville, f"Code postal auto-remplie depuis la ville: {ville}"
        else :
            return 5, code, ville, f"Ville invalide." 
        
    return 6, None, None, None